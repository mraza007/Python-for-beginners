"""Comparison operators all return True or False.

Run me:  python 02_comparison_operators.py
"""

print(5 == 5)    # True   equal to
print(5 != 3)    # True   not equal to
print(5 > 8)     # False  greater than
print(5 < 8)     # True   less than
print(5 >= 5)    # True   greater than or equal
print(4 <= 3)    # False  less than or equal

# Remember: = assigns, == compares.
x = 5            # assign 5 to x
print(x == 5)    # True   ask "is x equal to 5?"
