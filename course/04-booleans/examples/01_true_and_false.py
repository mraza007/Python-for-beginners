"""The two boolean values, and where they come from.

Run me:  python 01_true_and_false.py
"""

is_open = True
is_raining = False

print(is_open, type(is_open))   # True <class 'bool'>
print(is_raining)               # False

# Comparisons PRODUCE booleans — this is the usual source of True/False.
print(10 > 3)     # True
print(2 == 5)     # False
